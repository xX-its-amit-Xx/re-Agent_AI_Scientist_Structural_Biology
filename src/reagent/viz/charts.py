"""Dependency-free inline SVG charts.

Why hand-rolled SVG rather than matplotlib:

* **No dependency.** A teammate who only wants the contracts should not need a
  plotting stack, and `pip install matplotlib` is not free on a hackathon laptop.
* **Smaller and sharper.** A PNG has to be base64-embedded, costing about a third
  more bytes than its binary size, and it is fixed-resolution. Inline SVG is text,
  compresses well, and stays crisp.
* **Theme-aware.** The charts use CSS custom properties, so they follow the report's
  light or dark palette instead of shipping a baked-in white background that glares
  in dark mode.

The four shapes here are the ones `EXPECTED_VIZ` actually asks for across the
stages: a ranked bar, a heatmap, a distribution, and a scatter. Each returns an SVG
string and a matching ``Visualization``, so the declared encoding is generated by
the same code that draws the marks.

Everything is deliberately plain. These are report figures, not an interactive
plotting library; when a stage needs something genuinely bespoke it should write it
and declare its own encoding.
"""

from __future__ import annotations

import html
import math
from collections.abc import Sequence
from pathlib import Path

from reagent.contracts import ColorMap, Visualization, VizKind, VizMedium

#: Okabe-Ito, the same colour-blind-safe palette the graph renderer uses, so a
#: report's figures read as one system rather than as separate tools' output.
PALETTE = ["#0072B2", "#E69F00", "#009E73", "#CC79A7", "#56B4E9", "#D55E00",
           "#6A3D9A", "#454545"]

#: Sequential ramp for heatmaps. Light-to-dark blue: monotonic in lightness, so it
#: survives greyscale printing, which a rainbow ramp does not.
SEQUENTIAL = ["#f2f7fb", "#d5e5f2", "#a9cbe4", "#74a9d0", "#4180b8", "#1f5c99", "#0d3b6b"]

_CSS = """
  .rg-chart { font: 12px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; }
  .rg-chart text { fill: var(--ink, #1a1a1a); }
  .rg-chart .ax { stroke: var(--line, #d8d8d4); stroke-width: 1; }
  .rg-chart .grid { stroke: var(--line, #e8e8e4); stroke-width: 1; stroke-dasharray: 2 3; }
  .rg-chart .lab { font-size: 11px; fill: var(--muted, #5c5c5c); }
  .rg-chart .val { font-size: 10.5px; fill: var(--muted, #5c5c5c); }
  .rg-chart .ttl { font-size: 12.5px; font-weight: 600; }
"""


def _e(s: object) -> str:
    return html.escape(str(s), quote=True)


def _svg(w: int, h: int, body: str) -> str:
    return (
        f'<svg class="rg-chart" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
        f'width="100%" role="img"><style>{_CSS}</style>{body}</svg>'
    )


def _nice_ticks(lo: float, hi: float, n: int = 5) -> list[float]:
    """Round tick values. An axis labelled 0, 0.1732, 0.3464 is not readable."""
    if hi <= lo:
        return [lo]
    raw = (hi - lo) / max(1, n)
    mag = 10 ** math.floor(math.log10(raw))
    step = min((m * mag for m in (1, 2, 2.5, 5, 10) if m * mag >= raw), default=raw)
    start = math.floor(lo / step) * step
    out, v = [], start
    while v <= hi + step / 2:
        out.append(round(v, 10))
        v += step
    return out


def _write(svg: str, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as fh:
        fh.write(svg)
    return path


